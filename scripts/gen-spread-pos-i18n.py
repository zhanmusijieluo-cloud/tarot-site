def append_to_file(path, lines, marker):
    with open(path, encoding='utf-8') as f:
        content = f.read()
    # 在 marker 行后插入
    idx = content.index(marker) + len(marker)
    new_content = content[:idx] + '\n' + '\n'.join(lines) + content[idx:]
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(new_content)
    print(f"{path}: appended {len(lines)} keys")

