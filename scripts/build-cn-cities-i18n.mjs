const out = {};
for (const name of names) {
  // 拼音: 无声调, 首字母大写, 连写 (北京→Beijing, 门头沟→Mentougou)
  const syl = pinyin(name, { toneType: 'none', type: 'array', mode: 'proper-noun' });
  const pyRaw = syl.join('').replace(/ü/g, 'u');
  const py = pyRaw.charAt(0).toUpperCase() + pyRaw.slice(1).toLowerCase();
  // 日文: 逐字换形, 未命中保留原字 (中日同形字日本直接可读)
  const ja = [...name].map((ch) => JA_GLYPH[ch] ?? ch).join('');
  out[name] = { py, ja };
}

